-- V001__Master_Module.sql
-- Module 1: Master (Global Common) Schema Standardization
-- Renames and normalizes:
-- 1. MASTER_COUNTRY -> MST_COUNTRY
-- 2. MASTER_STATE -> MST_STATE
-- 3. product_master -> MST_PRODUCT
-- 4. FREIGHT_MASTER -> MST_FREIGHT
-- 5. MODE_OF_DESPATCH -> MST_DESPATCH_MODE

-- ==========================================
-- 1. MASTER_COUNTRY -> MST_COUNTRY
-- ==========================================
IF OBJECT_ID('MASTER_COUNTRY', 'U') IS NOT NULL
BEGIN
    IF OBJECT_ID('MST_COUNTRY', 'U') IS NULL
    BEGIN
        EXEC sp_rename 'MASTER_COUNTRY', 'MST_COUNTRY';
    END
    ELSE
    BEGIN
        DROP TABLE MASTER_COUNTRY;
    END
END
GO

IF COL_LENGTH('MST_COUNTRY', 'created_by') IS NOT NULL AND COL_LENGTH('MST_COUNTRY', 'CREATED_BY') IS NULL
BEGIN
    EXEC sp_rename 'MST_COUNTRY.created_by', 'CREATED_BY', 'COLUMN';
END
GO
IF COL_LENGTH('MST_COUNTRY', 'created_at') IS NOT NULL AND COL_LENGTH('MST_COUNTRY', 'CREATED_DATE') IS NULL
BEGIN
    EXEC sp_rename 'MST_COUNTRY.created_at', 'CREATED_DATE', 'COLUMN';
END
GO
IF COL_LENGTH('MST_COUNTRY', 'updated_by') IS NOT NULL AND COL_LENGTH('MST_COUNTRY', 'UPDATED_BY') IS NULL
BEGIN
    EXEC sp_rename 'MST_COUNTRY.updated_by', 'UPDATED_BY', 'COLUMN';
END
GO
IF COL_LENGTH('MST_COUNTRY', 'updated_at') IS NOT NULL AND COL_LENGTH('MST_COUNTRY', 'UPDATED_DATE') IS NULL
BEGIN
    EXEC sp_rename 'MST_COUNTRY.updated_at', 'UPDATED_DATE', 'COLUMN';
END
GO

IF OBJECT_ID('MST_COUNTRY', 'U') IS NOT NULL
BEGIN
    ALTER TABLE MST_COUNTRY ALTER COLUMN COUNTRY NVARCHAR(100) NOT NULL;
    ALTER TABLE MST_COUNTRY ALTER COLUMN STATUS NVARCHAR(20);
    ALTER TABLE MST_COUNTRY ALTER COLUMN CREATED_BY NVARCHAR(100);
    ALTER TABLE MST_COUNTRY ALTER COLUMN CREATED_DATE DATETIME;
    ALTER TABLE MST_COUNTRY ALTER COLUMN UPDATED_BY NVARCHAR(100);
    ALTER TABLE MST_COUNTRY ALTER COLUMN UPDATED_DATE DATETIME;
END
GO

IF OBJECT_ID('MST_COUNTRY', 'U') IS NOT NULL
BEGIN
    IF COL_LENGTH('MST_COUNTRY', 'IS_ACTIVE') IS NULL
    BEGIN
        ALTER TABLE MST_COUNTRY ADD IS_ACTIVE BIT DEFAULT 1;
    END
END
GO

-- Recreate Country Primary Key Constraint with Named PK
IF OBJECT_ID('MST_COUNTRY', 'U') IS NOT NULL
BEGIN
    DECLARE @country_pk NVARCHAR(256);
    SELECT TOP 1 @country_pk = name 
    FROM sys.key_constraints 
    WHERE parent_object_id = OBJECT_ID('MST_COUNTRY') AND type = 'PK';
    
    IF @country_pk IS NOT NULL AND @country_pk <> 'PK_MST_COUNTRY'
    BEGIN
        DECLARE @drop_country_pk NVARCHAR(MAX) = 'ALTER TABLE MST_COUNTRY DROP CONSTRAINT ' + @country_pk;
        EXEC(@drop_country_pk);
    END
    
    IF NOT EXISTS (SELECT 1 FROM sys.key_constraints WHERE parent_object_id = OBJECT_ID('MST_COUNTRY') AND name = 'PK_MST_COUNTRY')
    BEGIN
        ALTER TABLE MST_COUNTRY ADD CONSTRAINT PK_MST_COUNTRY PRIMARY KEY (id);
    END
END
GO


