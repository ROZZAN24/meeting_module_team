    BEGIN
        ALTER TABLE MST_COUNTRY ADD CONSTRAINT UQ_MST_COUNTRY_NAME UNIQUE (COUNTRY);
    END
END
GO

IF OBJECT_ID('MST_STATE', 'U') IS NOT NULL AND OBJECT_ID('MST_COUNTRY', 'U') IS NOT NULL
BEGIN
    -- Delete invalid country names to prevent FK constraint failure
    DELETE FROM MST_STATE WHERE COUNTRY_NAME NOT IN (SELECT COUNTRY FROM MST_COUNTRY);

    IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE object_id = OBJECT_ID('FK_MST_STATE_COUNTRY'))
    BEGIN
        ALTER TABLE MST_STATE ADD CONSTRAINT FK_MST_STATE_COUNTRY FOREIGN KEY (COUNTRY_NAME) REFERENCES MST_COUNTRY(COUNTRY);
    END
END
